
def bin_to_int():
    print(int('1001',2))
    print(int('1000',2))
    print(int('1111',2))
    print(int('10010',2))
    print(int('101',2))

def int_to_bin():
    print(bin(6))
    print(bin(10))
    print(bin(19))
    print(bin(32))

